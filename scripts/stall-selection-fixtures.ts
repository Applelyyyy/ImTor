import { readFile,writeFile } from "node:fs/promises";
import sharp from "sharp";
import { db } from "../src/lib/db";
import { StoreService } from "../src/services/products";
const url=new URL(process.env.DATABASE_URL!);
if(!["localhost","127.0.0.1"].includes(url.hostname)||!url.pathname.endsWith("_test")||process.env.NODE_ENV==="production")throw Error("Isolated local *_test only");
const path="test-results/fixtures.json";
const f=JSON.parse(await readFile(path,"utf8"));
const owner=await db.user.findUniqueOrThrow({where:{id:f.users[1].id}});
const store=await StoreService.create(owner,{name:f.tag+" ร้านทดสอบ",kind:"BOTH",address:"ทดสอบเท่านั้น"});
f.storeId=store.id;f.storeSlug=store.slug;
const large=await db.marketVenue.create({data:{slug:f.tag+"-large",name:"ตลาดใหญ่ทดสอบ",description:"เฉพาะทดสอบระบบ",entrance:"ฝั่งอาคารกิจกรรม (ทดสอบ)"}});
await db.marketVenue.update({where:{id:f.marketId},data:{name:"ตลาดเล็กทดสอบ"}});
const z=await db.marketZone.create({data:{marketId:large.id,name:"B"}});
const stalls=await Promise.all([["B11",.25,.35],["B12",.7,.6],["B13",.98,.98],["B00",0,0],["B14",.25,.35]].map(([code,x,y])=>db.marketStall.create({data:{marketId:large.id,zoneId:z.id,code:String(code),x:Number(x),y:Number(y)}})));
await db.marketStall.update({where:{id:stalls[2].id},data:{active:false}});
const smallZone=await db.marketZone.findFirstOrThrow({where:{marketId:f.marketId}});
await db.marketStall.create({data:{marketId:f.marketId,zoneId:smallZone.id,code:"A97",x:.2,y:.3}});
const start=new Date(Date.now()-60_000),end=new Date(Date.now()+3_600_000);
const session=await db.marketSession.create({data:{marketId:large.id,date:new Intl.DateTimeFormat("en-CA",{timeZone:"Asia/Bangkok"}).format(start),startsAt:start,endsAt:end}});
await db.marketSession.create({data:{marketId:large.id,date:"2026-10-01",startsAt:new Date("2026-10-01T01:00:00Z"),endsAt:new Date("2026-10-01T12:00:00Z"),status:"FINISHED"}});
await db.marketSession.create({data:{marketId:large.id,date:"2026-11-05",startsAt:new Date(Date.now()+86400_000*5),endsAt:new Date(Date.now()+86400_000*5+3600_000),status:"CANCELLED"}});
f.extraMarketId=large.id;f.largeMarketSlug=large.slug;f.largeSessionId=session.id;f.largeStallId=stalls[0].id;
await writeFile(path,JSON.stringify(f),{mode:0o600});
const svg=Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="600"><rect width="1200" height="600" fill="#f8f7e9"/><path d="M30 80H1170V570H30Z M600 80V570" fill="none" stroke="#327548" stroke-width="6"/><text x="80" y="50" font-size="30">LOCAL QA MARKET LAYOUT - NOT A REAL VENUE</text><text x="80" y="130" font-size="32">ZONE A</text><text x="680" y="130" font-size="32">ZONE B</text></svg>`);
await sharp(svg).png().toFile("test-results/market-layout-qa.png");
console.log("Created owned small/large market fixtures and original2:1 test-layout PNG");
await db.$disconnect();
